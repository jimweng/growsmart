func getLMSTable(gender, measureType string) []LMSPoint {
	switch measureType + "_" + gender {
	case "height_male":
		return heightBoysLMS
	case "height_female":
		return heightGirlsLMS
	case "weight_male":
		return weightBoysLMS
	case "weight_female":
		return weightGirlsLMS
	}
	return nil
}
